/**
 * Get verified authentic local image for any destination ID or slug.
 * Guarantees zero broken links and zero random rotations.
 */
export function getDestinationImage(slugOrId, fallback = DEFAULT_FALLBACK_IMAGE) {
  if (!slugOrId) return fallback || DEFAULT_FALLBACK_IMAGE;
  const clean = String(slugOrId).toLowerCase().trim().replace(/[\s_]+/g, '-');
  return DESTINATION_IMAGES[clean] || fallback || DEFAULT_FALLBACK_IMAGE;
}

